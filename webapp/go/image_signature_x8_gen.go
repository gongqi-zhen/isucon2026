//go:build ignore

// image_signature_amd64.s を作る。`go generate`（image_signature_amd64.go の go:generate）で実行する。
// 8本の HMAC-SHA256 の連鎖（hmacChainState）を、AVX-512VL の YMM レジスタ（1本の uint32 ずつ8レーン）で同時に進める。
//
// レジスタの割り当て：
//
//	Y0〜Y7：作業変数 a〜h（ラウンドごとに役割をずらす）
//	Y8〜Y15：一時
//	Y16〜Y31：メッセージのスケジュール W[0]〜W[15]（16語の循環）
//
// AVX-512VL の VPRORD（回転）と VPTERNLOGD（3入力の論理演算）を使うので、AVX2 だけの CPU では動かない。
package main

import (
	"fmt"
	"os"
	"strings"
)

var k = [64]uint32{
	0x428a2f98, 0x71374491, 0xb5c0fbcf, 0xe9b5dba5, 0x3956c25b, 0x59f111f1, 0x923f82a4, 0xab1c5ed5,
	0xd807aa98, 0x12835b01, 0x243185be, 0x550c7dc3, 0x72be5d74, 0x80deb1fe, 0x9bdc06a7, 0xc19bf174,
	0xe49b69c1, 0xefbe4786, 0x0fc19dc6, 0x240ca1cc, 0x2de92c6f, 0x4a7484aa, 0x5cb0a9dc, 0x76f988da,
	0x983e5152, 0xa831c66d, 0xb00327c8, 0xbf597fc7, 0xc6e00bf3, 0xd5a79147, 0x06ca6351, 0x14292967,
	0x27b70a85, 0x2e1b2138, 0x4d2c6dfc, 0x53380d13, 0x650a7354, 0x766a0abb, 0x81c2c92e, 0x92722c85,
	0xa2bfe8a1, 0xa81a664b, 0xc24b8b70, 0xc76c51a3, 0xd192e819, 0xd6990624, 0xf40e3585, 0x106aa070,
	0x19a4c116, 0x1e376c08, 0x2748774c, 0x34b0bcb5, 0x391c0cb3, 0x4ed8aa4a, 0x5b9cca4f, 0x682e6ff3,
	0x748f82ee, 0x78a5636f, 0x84c87814, 0x8cc70208, 0x90befffa, 0xa4506ceb, 0xbef9a3f7, 0xc67178f2,
}

var b strings.Builder

func emit(format string, args ...any) {
	fmt.Fprintf(&b, "\t"+format+"\n", args...)
}

func w(i int) string { return fmt.Sprintf("Y%d", 16+i%16) }

func main() {
	b.WriteString("// Code generated by image_signature_x8_gen.go. DO NOT EDIT.\n\n")
	b.WriteString("#include \"textflag.h\"\n\n")
	for i, v := range k {
		fmt.Fprintf(&b, "DATA hmacX8K<>+%d(SB)/4, $0x%08x\n", 4*i, v)
	}
	b.WriteString("GLOBL hmacX8K<>(SB), RODATA|NOPTR, $256\n\n")
	b.WriteString("DATA hmacX8Pad<>+0(SB)/4, $0x80000000\n")
	// 内側も外側も、64バイト（ipad／opad のブロック）＋32バイト＝96バイト＝768ビット。
	b.WriteString("DATA hmacX8Pad<>+4(SB)/4, $768\n")
	b.WriteString("GLOBL hmacX8Pad<>(SB), RODATA|NOPTR, $8\n\n")

	b.WriteString("// func hmacChainX8AVX512(st *hmacChainState, iterations int)\n")
	b.WriteString("TEXT ·hmacChainX8AVX512(SB), NOSPLIT, $0-16\n")
	emit("MOVQ st+0(FP), DI")
	emit("MOVQ iterations+8(FP), CX")
	emit("TESTQ CX, CX")
	emit("JZ done")
	b.WriteString("\niter:\n")
	// SI = ipad の状態、続いて opad の状態。どちらも value を受け取り、value に書き戻す。
	emit("MOVQ DI, SI")
	emit("MOVQ $2, DX")
	b.WriteString("\nphase:\n")
	// W[0..7] = value、W[8] = 0x80000000、W[9..14] = 0、W[15] = 768。
	for i := 0; i < 8; i++ {
		emit("VMOVDQU32 %d(DI), %s", 512+32*i, w(i))
	}
	emit("VPBROADCASTD hmacX8Pad<>+0(SB), %s", w(8))
	for i := 9; i < 15; i++ {
		emit("VPXORD %s, %s, %s", w(i), w(i), w(i))
	}
	emit("VPBROADCASTD hmacX8Pad<>+4(SB), %s", w(15))
	for i := 0; i < 8; i++ {
		emit("VMOVDQU %d(SI), Y%d", 32*i, i)
	}
	regs := []int{0, 1, 2, 3, 4, 5, 6, 7} // a..h
	for i := 0; i < 64; i++ {
		if i >= 16 {
			// W[i] = σ1(W[i-2]) + W[i-7] + σ0(W[i-15]) + W[i-16]
			w0, w1, w9, w14 := w(i), w(i+1), w(i+9), w(i+14)
			emit("VPRORD $7, %s, Y13", w1)
			emit("VPRORD $18, %s, Y14", w1)
			emit("VPSRLD $3, %s, Y15", w1)
			emit("VPTERNLOGD $0x96, Y15, Y14, Y13")
			emit("VPADDD Y13, %s, %s", w0, w0)
			emit("VPADDD %s, %s, %s", w9, w0, w0)
			emit("VPRORD $17, %s, Y13", w14)
			emit("VPRORD $19, %s, Y14", w14)
			emit("VPSRLD $10, %s, Y15", w14)
			emit("VPTERNLOGD $0x96, Y15, Y14, Y13")
			emit("VPADDD Y13, %s, %s", w0, w0)
		}
		a, bb, c, d, e, f, g, h := regs[0], regs[1], regs[2], regs[3], regs[4], regs[5], regs[6], regs[7]
		// h += K[i] + W[i] + Σ1(e) + Ch(e, f, g)
		emit("VPBROADCASTD hmacX8K<>+%d(SB), Y8", 4*i)
		emit("VPADDD %s, Y8, Y8", w(i))
		emit("VPADDD Y8, Y%d, Y%d", h, h)
		emit("VPRORD $6, Y%d, Y9", e)
		emit("VPRORD $11, Y%d, Y10", e)
		emit("VPRORD $25, Y%d, Y11", e)
		emit("VPTERNLOGD $0x96, Y11, Y10, Y9")
		emit("VPADDD Y9, Y%d, Y%d", h, h)
		emit("VMOVDQA Y%d, Y12", e)
		emit("VPTERNLOGD $0xca, Y%d, Y%d, Y12", g, f)
		emit("VPADDD Y12, Y%d, Y%d", h, h)
		// d += T1（次の e）
		emit("VPADDD Y%d, Y%d, Y%d", h, d, d)
		// h = T1 + Σ0(a) + Maj(a, b, c)（次の a）
		emit("VPRORD $2, Y%d, Y9", a)
		emit("VPRORD $13, Y%d, Y10", a)
		emit("VPRORD $22, Y%d, Y11", a)
		emit("VPTERNLOGD $0x96, Y11, Y10, Y9")
		emit("VMOVDQA Y%d, Y12", a)
		emit("VPTERNLOGD $0xe8, Y%d, Y%d, Y12", c, bb)
		emit("VPADDD Y9, Y%d, Y%d", h, h)
		emit("VPADDD Y12, Y%d, Y%d", h, h)
		regs = []int{h, a, bb, c, d, e, f, g}
	}
	// 64ラウンドで役割は一周するので、regs は元の並びに戻っている。状態を足して value に書く。
	for i := 0; i < 8; i++ {
		emit("VPADDD %d(SI), Y%d, Y%d", 32*i, regs[i], regs[i])
		emit("VMOVDQU Y%d, %d(DI)", regs[i], 512+32*i)
	}
	emit("ADDQ $256, SI")
	emit("DECQ DX")
	emit("JNZ phase")
	emit("DECQ CX")
	emit("JNZ iter")
	b.WriteString("\ndone:\n")
	emit("VZEROUPPER")
	emit("RET")

	if err := os.WriteFile("image_signature_amd64.s", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
}
